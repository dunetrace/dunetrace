"""Calibration corpus for MALFORMED_TOOL_CALL.

A fixed, hand-labelled set of tool-argument strings: the malformed JSON an LLM
actually writes (positives) and the bracket-leading plain text and valid
payloads real tools receive (negatives), including the encodings Dunetrace's
own SDKs and integrations produce. Offline and deterministic.

    PYTHONPATH=packages/sdk-py python scripts/calibrate_malformed_tool_call.py \
        --report scripts/calibration/malformed_tool_call_calibration.md

Exit status is non-zero when the corpus breaks the gates in
docs/contributing/adding-a-detector.md (false-positive rate < 15%, recall >= 50%).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from dunetrace.detectors import MalformedToolCallDetector
from dunetrace.models import RunState, ToolCall
from dunetrace.redaction import serialize_capped

FP_GATE = 0.15
RECALL_GATE = 0.50

# (label, args, is_malformed)
CORPUS = [
    # Malformed JSON an LLM writes in a tool call.
    ("trailing comma in object", '{"title": "x", "priority": "high",}', True),
    ("trailing comma in array", "[1, 2, 3,]", True),
    ("single-quoted keys", "{'title': 'x'}", True),
    ("Python True", '{"done": True}', True),
    ("Python None", '{"assignee": None}', True),
    ("bare NaN", '{"score": NaN}', True),
    ("NaN array", "[NaN]", True),
    ("Infinity array", "[Infinity]", True),
    ("negative Infinity array", "[-Infinity]", True),
    ("set-like object", '{"title", "body"}', True),
    ("invalid escape", '{"pattern": "\\d+"}', True),
    ("missing value", '{"title": }', True),
    ("unterminated object", '{"title": "Refund", "body": "late"', True),
    ("unquoted key", '{title: "x"}', True),  # malformed, but not judged by shape: documented miss
    ("comment inside JSON", '{"a": 1 // note\n}', True),
    ("LangChain raw malformed input", '{"title": }', True),
    # Plain text that starts with a bracket.
    ("GraphQL query", "{ user(id: 1) { name } }", False),
    ("log line", "[INFO] restart service", False),
    ("markdown link", "[docs](https://example.com)", False),
    ("Python list comprehension", "[x * 2 for x in range(3)]", False),
    ("template", "{name}, your order shipped", False),
    ("shell test", "[ -f /tmp/x ] && cat /tmp/x", False),
    ("failed JS stringify", "[object Object]", False),
    ("bracketed NaN-like text", "[NaNish]", False),
    ("bracketed Infinity-like text", "[InfinityPool]", False),
    ("free text", "refund policy for damaged goods", False),
    # Valid payloads, including the SDKs' own encodings.
    ("valid object", '{"query": "refunds", "limit": 5}', False),
    ("valid array", '[{"id": 1}, {"id": 2}]', False),
    ("empty object", "{}", False),
    ("LangChain-wrapped plain input", json.dumps({"input": "refund policy"}), False),
    ("valid input containing Python code", json.dumps({"input": "{'a': 1}"}), False),
    ("valid input containing broken JSON", json.dumps({"input": '{"title": }'}), False),
    (
        "SDK: dict with UUID key",
        serialize_capped({__import__("uuid").UUID(int=1): 1}, None)[0],
        False,
    ),
    (
        "SDK: dict with datetime value",
        serialize_capped({"at": __import__("datetime").date(2026, 1, 1)}, None)[0],
        False,
    ),
    ("SDK: NaN value", serialize_capped({"x": float("nan")}, None)[0], False),
]


def fires(args: str) -> bool:
    state = RunState(run_id="cal", agent_id="cal", agent_version="v")
    state.tool_calls = [ToolCall(tool_name="t", args=args, step_index=1, timestamp=0.0)]
    return MalformedToolCallDetector().on_run_completion(state) is not None


def _rate(num: int, den: int) -> str:
    return f"{num / den:.1%}" if den else "n/a"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()

    tp = fp = fn = tn = 0
    false_positives, misses = [], []
    for label, text, positive in CORPUS:
        fired = fires(text)
        tp += fired and positive
        fp += fired and not positive
        fn += positive and not fired
        tn += not fired and not positive
        if fired and not positive:
            false_positives.append(label)
        if positive and not fired:
            misses.append(label)
        print(f"{'FIRE' if fired else '----'}  {'+' if positive else '-'}  {label}")

    fp_rate = fp / (fp + tn) if fp + tn else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    ok = fp_rate < FP_GATE and recall >= RECALL_GATE
    summary = (
        f"TP {tp}, FP {fp}, FN {fn}, TN {tn}; recall {_rate(tp, tp + fn)}, "
        f"false-positive rate {_rate(fp, fp + tn)}, precision {_rate(tp, tp + fp)}."
    )
    print(summary, "PASS" if ok else "FAIL")

    if args.report:
        args.report.write_text(
            "# MALFORMED_TOOL_CALL: calibration corpus\n\n"
            "Generated by `PYTHONPATH=packages/sdk-py python scripts/calibrate_malformed_tool_call.py "
            "--report scripts/calibration/malformed_tool_call_calibration.md`. Offline and "
            "deterministic.\n\n"
            f"{len(CORPUS)} hand-labelled argument strings: malformed JSON an LLM writes, "
            "bracket-leading plain text, valid payloads, and the encodings Dunetrace's own SDKs "
            f"produce.\n\n{summary}\n\n"
            f"Gates (docs/contributing/adding-a-detector.md): false-positive rate < {FP_GATE:.0%}, "
            f"recall >= {RECALL_GATE:.0%}. Result: **{'pass' if ok else 'fail'}**.\n\n"
            f"Negatives that fired: {', '.join(false_positives) or 'none'}.\n\n"
            f"Positives missed: {', '.join(misses) or 'none'}. An unquoted key (`{{title: ...}}`) "
            "does not open like JSON, so it is deliberately not judged: allowing a bare identifier "
            "after `{` would also judge GraphQL queries and templates.\n\n"
            "This is a boundary corpus, not a production precision estimate. Before promoting "
            "the detector out of shadow, measure its fire rate on real traffic per framework: "
            "a caller that records `str(some_dict)` as the args string will fire it, by design.\n",
            encoding="utf-8",
        )
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
