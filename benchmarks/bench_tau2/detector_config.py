"""The detectors.yml the replay worker reads.

It is the shipped detectors.yml, byte for byte, with one section appended per
agent. Each appended section sets a single value:
UNRESOLVED_AMBIGUITY's IRREVERSIBLE_TOOLS, which ships empty because only the
operator can declare it. The harness declares the tools τ²-bench annotates as
ToolType.WRITE for that domain. Nothing else is set, so every threshold is
the shipped default. The generated file lives in the cache directory and is
never committed or mounted into a real service.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Iterable, Tuple

from bench_tau2._paths import REPO_ROOT
from bench_tau2.tools import irreversible_tools

SHIPPED_CONFIG = REPO_ROOT / "detectors.yml"


def render(agents: Iterable[Tuple[str, str]]) -> str:
    """The shipped file plus a section per (agent_id, domain)."""
    text = SHIPPED_CONFIG.read_text()
    if not text.endswith("\n"):
        text += "\n"
    lines = [
        "",
        "# ---- tau2 benchmark harness (generated by benchmarks/bench_tau2, never shipped) ----",
        "# One section per replayed agent. The only value set is UNRESOLVED_AMBIGUITY's",
        "# operator-declared IRREVERSIBLE_TOOLS: tau2-bench's own ToolType.WRITE tools.",
    ]
    for agent_id, domain in sorted(set(agents)):
        tools = json.dumps(irreversible_tools(domain))
        lines += [
            f"{json.dumps(agent_id)}:",
            "  unresolved_ambiguity:",
            f"    irreversible_tools: {tools}",
        ]
    return text + "\n".join(lines) + "\n"


def write(path: Path, agents: Iterable[Tuple[str, str]]) -> str:
    """Write the config and return its SHA-256."""
    body = render(agents)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    return hashlib.sha256(body.encode()).hexdigest()
